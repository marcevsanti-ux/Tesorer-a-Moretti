'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('mesa-de-ayuda.html','utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(Boolean);
assert(scripts.length,'No se encontraron scripts embebidos');
for(const code of scripts)new vm.Script(code,{filename:'mesa-de-ayuda.html'});
assert(!html.includes('slaTargetHours'),'Quedó el control antiguo en horas');
assert(html.includes('slaTargetDays'),'Falta objetivo en días hábiles');
assert(!html.includes("field('Asunto','asunto'"),'Asunto sigue visible en formulario');
assert(html.includes('f.asunto=f.cliente_reclamo'),'Falta compatibilidad con columna asunto');
const start=html.indexOf('function kpiDateKey(');
const end=html.indexOf('function kpiClaimField(',start);
assert(start>=0&&end>start,'No se encontró cálculo de SLA');
const code=html.slice(start,end);
const context={Date,Set,Map,console,fetch:()=>{throw Error('No debería consultar red')},renderIndicadores:()=>{}};
vm.createContext(context);
vm.runInContext('const kpiHolidays=new Map(); const kpiHolidayPending=new Set(); const kpiHolidayFailed=new Set(); '+code,context);
vm.runInContext("kpiHolidays.set(2026,new Set(['2026-11-09']))",context);
const days=(a,b)=>vm.runInContext('kpiBusinessDays('+a+','+b+')',context);
const ms=(date)=>new Date(date).getTime();
const friday=ms('2026-11-06T15:00:00-03:00');
const monday=ms('2026-11-09T10:00:00-03:00');
assert.equal(days(friday,monday),0.2,'Feriado lunes: deben contarse solo 2h viernes');
vm.runInContext('kpiHolidays.set(2026,new Set())',context);
assert.equal(days(friday,monday),0.5,'Viernes 15 a lunes 10 debe ser 0,5 días');
console.log('OK: sintaxis JavaScript, formulario y cálculo SLA');

const partFn=html.slice(html.indexOf('function isMissingPart('),html.indexOf('function render(){',html.indexOf('function isMissingPart(')));
assert(partFn.includes('function isMissingPart'),'Falta detección de repuesto');
const otCtx={};vm.createContext(otCtx);
vm.runInContext("function isFinalizada(ot){return /^finalizad[oa]$/i.test(String(ot.estado||'').trim());}"+partFn,otCtx);
const missing=ot=>vm.runInContext('isMissingPart('+JSON.stringify(ot)+')',otCtx);
assert.equal(missing({estado:'Pendiente',subestado:'7 - Falta de Repuesto'}),true,'La OT 71663 debe ser prioritaria');
assert.equal(missing({estado:'Pendiente',subestado:'8 - Garantia'}),false,'Garantía no debe ser prioritaria');
assert.equal(missing({estado:'Finalizado',subestado:'Finalizado'}),false,'La OT 71743 no debe figurar como falta de repuesto');
assert(html.includes('prefers-reduced-motion:reduce'),'Debe respetarse movimiento reducido');
console.log('OK: priorización de falta de repuesto y exclusión de finalizadas');
